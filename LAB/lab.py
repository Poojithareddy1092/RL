# Epsilon Greedy
def epsilon_greedy():
    count=[0]*3
    reward=[0]*3
    total=0

    for _ in range(rounds):
        if random.random()<0.1:
            a=random.randint(0,2)
        else:
            a=reward.index(max(reward))

        sale=random.random()<prob[a]
        r=prices[a] if sale else 0

        count[a]+=1
        reward[a]+=r
        total+=r

    return total


# UCB
def ucb():
    count=[0]*3
    reward=[0]*3
    total=0

    for t in range(1,rounds+1):

        if t<=3:
            a=t-1
        else:
            ucb_values=[
                reward[i]/count[i]+math.sqrt(2*math.log(t)/count[i])
                for i in range(3)
            ]
            a=ucb_values.index(max(ucb_values))

        sale=random.random()<prob[a]
        r=prices[a] if sale else 0

        count[a]+=1
        reward[a]+=r
        total+=r

    return total


# Thompson Sampling
def thompson():
    success=[1]*3
    fail=[1]*3
    total=0

    for _ in range(rounds):

        samples=[
            random.betavariate(success[i],fail[i])
            for i in range(3)
        ]

        a=samples.index(max(samples))

        sale=random.random()<prob[a]
        r=prices[a] if sale else 0

        if sale:
            success[a]+=1
        else:
            fail[a]+=1

        total+=r

    return total


print("Revenue Comparison")
print("Epsilon Greedy:", epsilon_greedy())
print("UCB:", ucb())
print("Thompson Sampling:", thompson())

