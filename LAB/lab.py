# Place dirt
for d in dirt:
    r, c = cell_to_pos(d)
    grid[r][c] = "D"

# Place obstacles
for o in obstacles:
    r, c = cell_to_pos(o)
    grid[r][c] = "X"

# Starting point
robot = [0, 0]
grid[0][0] = "R"

display_grid(grid)


# MDP Simulation

actions = [(0,1), (1,0), (0,-1), (-1,0)]
# Right, Down, Left, Up

action_names = ["Right", "Down", "Left", "Up"]

visited_dirt = set()
total_reward = 0


print("\nRobot Navigation:")

for step in range(50):

    r, c = robot
    moved = False

    for i, action in enumerate(actions):

        nr = r + action[0]
        nc = c + action[1]

        if 0 <= nr < 5 and 0 <= nc < 5:

            cell = pos_to_cell(nr,nc)

            # Avoid obstacles
            if cell not in obstacles:

                print("Action:", action_names[i])

                robot = [nr,nc]
                moved = True


                # Collect dirt
                if cell in dirt and cell not in visited_dirt:
                    print("Cleaned dirt at cell", cell)
                    visited_dirt.add(cell)
                    total_reward += 1


                break


    if not moved:
        print("No possible movement")
        break


    if len(visited_dirt) == len(dirt):
        print("\nAll dirt cleaned!")
        break


