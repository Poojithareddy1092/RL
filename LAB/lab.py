# Convert cell number to grid position
def cell_to_pos(cell):
    return ((cell - 1) // 5, (cell - 1) % 5)

# Convert grid position to cell number
def pos_to_cell(row, col):
    return row * 5 + col + 1


# Display Grid
def display_grid(grid):
    print("\nGrid:")
    for row in grid:
        print(" ".join(row))


