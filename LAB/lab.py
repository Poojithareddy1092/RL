def monte_carlo(policy):
    value=[0]*rep
    count=[0]*rep

    for _ in range(calls):

        if policy=="Random":
            r=random.randint(0,rep-1)

        else:  # Best available policy
            r=value.index(max(value))

        reward=random.randint(1,10)  # customer satisfaction

        count[r]+=1
        value[r]+= (reward-value[r])/count[r]

    return value


